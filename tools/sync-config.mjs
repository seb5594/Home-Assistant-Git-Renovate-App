const quote = (value) => JSON.stringify(String(value));

/** The schema type of a setting, as Home Assistant writes it. */
function schemaType(definition) {
  switch (definition.type) {
    case 'bool': return 'bool?';
    case 'int': return `int(${definition.min},${definition.max})?`;
    case 'enum': return `list(${definition.values.join('|')})?`;
    case 'secret': return 'password?';
    case 'url': return 'url?';
    default: return 'str?';
  }
}

function schemaLines(definition, indent) {
  const pad = ' '.repeat(indent);
  const name = nameOf(definition.key);
  if (definition.type === 'list') return [`${pad}${name}:`, `${pad}  - str`];
  if (definition.type === 'records') {
    return [`${pad}${name}:`, ...definition.fields.map((field, index) => {
      const type = field.type === 'secret' ? (field.required ? 'password' : 'password?') : (field.required ? 'str' : 'str?');
      return `${pad}  ${index === 0 ? '- ' : '  '}${field.key}: ${type}`;
    })];
  }
  return [`${pad}${name}: ${schemaType(definition)}`];
}

function buildConfigTail() {
  const options = ['options:'];
  const schema = ['schema:'];
  for (const group of GROUPS) {
    const entries = DEFINITIONS.filter((definition) => groupOf(definition.key) === group);
    const defaults = entries.filter((definition) => ['list', 'records'].includes(definition.type));
    if (defaults.length === 0) options.push(`  ${group}: {}`);
    else options.push(`  ${group}:`, ...defaults.map((definition) => `    ${nameOf(definition.key)}: []`));
    schema.push(`  ${group}:`, ...entries.flatMap((definition) => schemaLines(definition, 4)));
  }
  options.push('  connections: []');
  schema.push('  connections:',
    '    - name: str',
    '      provider: list(github|gitlab|gitea|forgejo)',
    '      url: url?',
    '      token: password',
    '      repositories: str?',
    '      include: str?',
    '      exclude: str?');
  return [...options, ...schema].join('\n');
}

function translationFile(code) {
  const messages = locales[code];
  const lines = ['configuration:'];
  for (const group of GROUPS) {
    lines.push(`  ${group}:`, `    name: ${quote(messages[`settings.group.${group}`])}`, `    description: ${quote(messages[`settings.group.${group}.help`])}`, '    fields:');
    for (const definition of DEFINITIONS.filter((candidate) => groupOf(candidate.key) === group)) {
      lines.push(`      ${nameOf(definition.key)}:`, `        name: ${quote(messages[`settings.${definition.key}.label`])}`, `        description: ${quote(messages[`settings.${definition.key}.help`])}`);
      if (definition.type === 'records') {
        lines.push('        fields:');
        for (const field of definition.fields) {
          const text = messages[`settings.${definition.key}.field.${field.key}`];
          lines.push(`          ${field.key}:`, `            name: ${quote(text)}`, `            description: ${quote(text)}`);
        }
      }
    }
  }
  const connections = CONNECTIONS[code];
  lines.push('  connections:', `    name: ${quote(connections.name)}`, `    description: ${quote(connections.description)}`, '    fields:');
  for (const [field, [name, description]] of Object.entries(connections.fields)) {
    lines.push(`      ${field}:`, `        name: ${quote(name)}`, `        description: ${quote(description)}`);
  }
  return `${lines.join('\n')}\n`;
}

const REFERENCE_TITLES = {
  en: { option: 'Option', description: 'Description', default: 'Default', automatic: 'automatic', none: 'none', locked: 'Only in the app configuration' },
  de: { option: 'Option', description: 'Beschreibung', default: 'Standard', automatic: 'automatisch', none: 'keiner', locked: 'Nur in der App-Konfiguration' },
};

/** The options reference of the documentation, one table per group. */
function optionsReference(code) {
  const messages = locales[code];
  const words = REFERENCE_TITLES[code];
  const show = (definition) => {
    if (definition.type === 'secret') return '–';
    if (definition.default === undefined || definition.default === null) return words.automatic;
    if (Array.isArray(definition.default)) return words.none;
    return `\`${definition.default}\``;
  };
  const blocks = [];
  for (const group of GROUPS) {
    blocks.push(`### ${messages[`settings.group.${group}`]}`, '', messages[`settings.group.${group}.help`], '',
      `| ${words.option} | ${words.description} | ${words.default} |`, '| --- | --- | --- |');
    for (const definition of DEFINITIONS.filter((candidate) => groupOf(candidate.key) === group)) {
      const note = definition.scope === 'options-only' ? ` *(${words.locked})*` : '';
      blocks.push(`| \`${definition.key}\`<br>**${messages[`settings.${definition.key}.label`]}** | ${messages[`settings.${definition.key}.help`]}${note} | ${show(definition)} |`);
    }
    blocks.push('');
  }
  return blocks.join('\n');
}

const configPath = path.join(app, 'config.yaml');
const current = readFileSync(configPath, 'utf8');
const head = current.includes(MARKER) ? current.slice(0, current.indexOf(MARKER)) : `${current.trimEnd()}\n`;
const files = new Map([[configPath, `${head}${MARKER}\n${buildConfigTail()}\n`]]);
for (const code of LANGUAGES) files.set(path.join(app, `translations/${code}.yaml`), translationFile(code));

for (const [code, name] of [['en', 'DOCS.md'], ['de', 'DOCS.de.md']]) {
  const file = path.join(app, name);
  const text = readFileSync(file, 'utf8');
  const begin = '<!-- options:begin -->';
  const end = '<!-- options:end -->';
  files.set(file, `${text.slice(0, text.indexOf(begin) + begin.length)}\n\n${optionsReference(code)}\n${text.slice(text.indexOf(end))}`);
}

const stale = [];
for (const [file, text] of files) {
  let existing = null;
  try { existing = readFileSync(file, 'utf8'); } catch { /* not there yet */ }
  if (existing !== text) {
    stale.push(path.relative(root, file));
    if (!process.argv.includes('--check')) {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
}
if (process.argv.includes('--check')) {
  if (stale.length) {
    console.error(`Out of date, run "node tools/sync-config.mjs": ${stale.join(', ')}`);
    process.exit(1);
  }
} else {
  console.log(stale.length ? `Updated: ${stale.join(', ')}` : 'Already up to date.');
}
